-- Σχήμα PostgreSQL (Supabase). Εκτελείται αυτόματα από την εφαρμογή στην εκκίνηση
-- (idempotent: CREATE ... IF NOT EXISTS). Μπορεί να εκτελεστεί και χειροκίνητα στο
-- Supabase SQL Editor.
--
-- Χρονοσφραγίδες: ISO-8601 UTC ως TEXT (ίδια μορφή με την τοπική έκδοση SQLite,
-- λεξικογραφική ταξινόμηση = χρονολογική).
-- Κιλά: Decimal ως TEXT (ακριβής αριθμητική στην Python, ποτέ float).

CREATE TABLE IF NOT EXISTS schema_meta (
    key   TEXT PRIMARY KEY,
    value TEXT NOT NULL
);

-- Εκδόσεις εισαγωγής Excel. Τα αρχεία βρίσκονται στο Supabase Storage (private bucket).
CREATE TABLE IF NOT EXISTS excel_imports (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    original_filename   TEXT    NOT NULL,
    original_object     TEXT    NOT NULL DEFAULT '',   -- αναλλοίωτο αρχικό αρχείο
    working_object      TEXT    NOT NULL DEFAULT '',   -- τρέχουσα έκδοση working Excel
    working_version     INTEGER NOT NULL DEFAULT 0,    -- αυξάνεται σε κάθε μεταφορά (version check)
    working_sha256      TEXT    NOT NULL DEFAULT '',
    original_sha256     TEXT    NOT NULL,
    imported_at         TEXT    NOT NULL,
    imported_by         TEXT    NOT NULL,
    status              TEXT    NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'ready', 'failed')),
    is_active           INTEGER NOT NULL DEFAULT 0 CHECK (is_active IN (0, 1)),
    product_count       INTEGER NOT NULL,
    unique_barcodes     INTEGER NOT NULL,
    duplicate_barcodes  INTEGER NOT NULL,
    source_sheet        TEXT    NOT NULL,
    target_sheet        TEXT    NOT NULL,
    notes               TEXT
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_imports_single_active ON excel_imports(is_active) WHERE is_active = 1;

-- Αρχεία που ανέβηκαν και ελέγχθηκαν αλλά δεν ενεργοποιήθηκαν ακόμη.
CREATE TABLE IF NOT EXISTS staged_uploads (
    id           TEXT PRIMARY KEY,
    filename     TEXT NOT NULL,
    object_path  TEXT NOT NULL,
    sha256       TEXT NOT NULL,
    uploaded_by  TEXT NOT NULL,
    uploaded_at  TEXT NOT NULL,
    report_json  TEXT NOT NULL
);

-- Γραμμές του φύλλου πηγής: κατάλογος γρήγορης αναζήτησης barcode.
CREATE TABLE IF NOT EXISTS product_records (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    import_id     BIGINT  NOT NULL REFERENCES excel_imports(id),
    sheet_row     INTEGER NOT NULL,
    barcode       TEXT    NOT NULL,
    barcode_norm  TEXT    NOT NULL,
    eidos         TEXT,
    paxos         TEXT,
    diastaseis    TEXT,
    temaxia       TEXT,
    kila          TEXT,
    pelatis       TEXT,
    vspg          TEXT,
    topothesia    TEXT,
    thesi         TEXT,
    rolo          TEXT,
    extra_json    TEXT,
    fingerprint   TEXT    NOT NULL,
    group_key     TEXT    NOT NULL,
    status        TEXT    NOT NULL DEFAULT 'available' CHECK (status IN ('available', 'transferred')),
    transferred_at TEXT
);
CREATE INDEX IF NOT EXISTS ix_products_lookup ON product_records(import_id, barcode_norm);
CREATE INDEX IF NOT EXISTS ix_products_fp ON product_records(import_id, fingerprint);

-- Ενεργή λίστα (κοινή για αποθήκη και γραμματεία).
CREATE TABLE IF NOT EXISTS active_items (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    barcode             TEXT    NOT NULL,
    barcode_norm        TEXT    NOT NULL,
    state               TEXT    NOT NULL CHECK (state IN ('ok', 'ambiguous', 'unknown')),
    product_record_id   BIGINT REFERENCES product_records(id),
    import_id           BIGINT REFERENCES excel_imports(id),
    first_scan_event_id BIGINT,
    duplicate_count     INTEGER NOT NULL DEFAULT 0,
    created_at          TEXT    NOT NULL,
    status              TEXT    NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'transferred', 'removed')),
    closed_at           TEXT,
    closed_by           TEXT,
    close_reason        TEXT
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_active_barcode ON active_items(barcode_norm) WHERE status = 'active';
CREATE INDEX IF NOT EXISTS ix_active_status ON active_items(status);

-- Μόνιμο ιστορικό κάθε σκαναρίσματος. Το event_id (UUID του browser) είναι UNIQUE:
-- η επαναποστολή ίδιου scan δεν δημιουργεί δεύτερη εγγραφή (idempotency).
CREATE TABLE IF NOT EXISTS scan_events (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id         TEXT    NOT NULL UNIQUE,
    barcode          TEXT    NOT NULL,
    barcode_norm     TEXT    NOT NULL,
    client_ts        TEXT,
    received_at      TEXT    NOT NULL,
    device_id        TEXT,
    client_seq       BIGINT,
    result           TEXT    NOT NULL CHECK (result IN ('ok', 'duplicate', 'unknown', 'ambiguous', 'no_catalog', 'invalid')),
    message          TEXT,
    product_record_id BIGINT REFERENCES product_records(id),
    product_snapshot TEXT,
    pelatis          TEXT,
    kila             TEXT,
    import_id        BIGINT REFERENCES excel_imports(id),
    active_item_id   BIGINT REFERENCES active_items(id)
);
CREATE INDEX IF NOT EXISTS ix_scans_received ON scan_events(received_at);
CREATE INDEX IF NOT EXISTS ix_scans_barcode ON scan_events(barcode_norm);
CREATE INDEX IF NOT EXISTS ix_scans_active ON scan_events(active_item_id);

-- Operation journal μεταφορών. Η αλλαγή του working Excel "δεσμεύεται" μόνο όταν, στο
-- ΙΔΙΟ transaction, ενημερωθεί ο δείκτης excel_imports.working_version (version check)
-- και η εγγραφή γίνει 'completed'.
CREATE TABLE IF NOT EXISTS transfer_operations (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    active_item_id     BIGINT REFERENCES active_items(id),
    product_record_id  BIGINT NOT NULL REFERENCES product_records(id),
    import_id          BIGINT NOT NULL REFERENCES excel_imports(id),
    barcode            TEXT    NOT NULL,
    fingerprint        TEXT    NOT NULL,
    status             TEXT    NOT NULL CHECK (status IN ('started', 'completed', 'failed')),
    mode               TEXT,
    requested_by       TEXT    NOT NULL,
    started_at         TEXT    NOT NULL,
    finished_at        TEXT,
    source_row         INTEGER,
    target_row         INTEGER,
    base_version       INTEGER,
    base_object        TEXT,                 -- προηγούμενη έκδοση (backup, δεν σβήνεται ποτέ)
    excel_before_sha256 TEXT,
    new_object         TEXT,
    excel_after_sha256  TEXT,
    warning            TEXT,
    error              TEXT
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_transfer_once ON transfer_operations(product_record_id)
    WHERE status IN ('started', 'completed');

-- Leases για ενέργειες που διαρκούν πέρα από ένα DB transaction (εγγραφή Excel).
CREATE TABLE IF NOT EXISTS app_locks (
    name        TEXT PRIMARY KEY,
    holder      TEXT NOT NULL,
    expires_at  TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS audit_log (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ts       TEXT NOT NULL,
    actor    TEXT NOT NULL,
    action   TEXT NOT NULL,
    details  TEXT
);
CREATE INDEX IF NOT EXISTS ix_audit_ts ON audit_log(ts);

CREATE TABLE IF NOT EXISTS app_settings (
    key   TEXT PRIMARY KEY,
    value TEXT NOT NULL
);

-- ===========================================================================
-- Αναβάθμιση σχήματος v3 (ιδεμποτική — ασφαλής σε κάθε εκκίνηση και σε υπάρχουσα βάση):
--   * ουρά μεταφορών: η μεταφορά καταχωρίζεται αμέσως (queued) και το Excel ενημερώνεται
--     στο παρασκήνιο, πολλές μεταφορές μαζί σε ΜΙΑ νέα έκδοση (seq = σειρά μέσα στην έκδοση)
--   * επαναφορά λανθασμένης μεταφοράς (kind='restore', restore_of, reverted_at)
--   * διόρθωση barcode στα «Προς έλεγχο» (active_items.original_barcode)
-- ===========================================================================
ALTER TABLE transfer_operations ADD COLUMN IF NOT EXISTS kind TEXT NOT NULL DEFAULT 'transfer';
ALTER TABLE transfer_operations ADD COLUMN IF NOT EXISTS seq INTEGER;
ALTER TABLE transfer_operations ADD COLUMN IF NOT EXISTS restore_of BIGINT;
ALTER TABLE transfer_operations ADD COLUMN IF NOT EXISTS reverted_at TEXT;
ALTER TABLE transfer_operations ADD COLUMN IF NOT EXISTS reverted_by TEXT;
ALTER TABLE transfer_operations ADD COLUMN IF NOT EXISTS queued_at TEXT;
ALTER TABLE transfer_operations ADD COLUMN IF NOT EXISTS attempts INTEGER NOT NULL DEFAULT 0;
ALTER TABLE transfer_operations ADD COLUMN IF NOT EXISTS kila TEXT;
ALTER TABLE active_items ADD COLUMN IF NOT EXISTS original_barcode TEXT;
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'transfer_operations_status_check'
                   AND pg_get_constraintdef(oid) LIKE '%queued%') THEN
        ALTER TABLE transfer_operations DROP CONSTRAINT IF EXISTS transfer_operations_status_check;
        ALTER TABLE transfer_operations ADD CONSTRAINT transfer_operations_status_check
            CHECK (status IN ('queued', 'started', 'completed', 'failed'));
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'transfer_operations_kind_check') THEN
        ALTER TABLE transfer_operations ADD CONSTRAINT transfer_operations_kind_check
            CHECK (kind IN ('transfer', 'restore'));
    END IF;
END $$;
-- Μία ενεργή μεταφορά ανά προϊόν (μια επαναφορά "ελευθερώνει" το προϊόν για νέα μεταφορά).
DROP INDEX IF EXISTS ux_transfer_once;
CREATE UNIQUE INDEX IF NOT EXISTS ux_transfer_active ON transfer_operations(product_record_id)
    WHERE kind = 'transfer' AND status IN ('queued', 'started', 'completed') AND reverted_at IS NULL;
-- Μία επαναφορά ανά μεταφορά.
CREATE UNIQUE INDEX IF NOT EXISTS ux_restore_once ON transfer_operations(restore_of)
    WHERE kind = 'restore' AND status IN ('queued', 'started', 'completed');
CREATE INDEX IF NOT EXISTS ix_transfer_status ON transfer_operations(status);
CREATE INDEX IF NOT EXISTS ix_transfer_item ON transfer_operations(active_item_id);

-- Ασφάλεια Supabase: οι πίνακες ΔΕΝ πρέπει να είναι προσβάσιμοι μέσω του δημόσιου REST API
-- (anon / authenticated keys). Η εφαρμογή συνδέεται ως owner (postgres) και δεν επηρεάζεται.
DO $$
DECLARE t TEXT;
BEGIN
    FOREACH t IN ARRAY ARRAY['schema_meta','excel_imports','staged_uploads','product_records','active_items',
                             'scan_events','transfer_operations','app_locks','audit_log','app_settings']
    LOOP
        EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
        IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
            EXECUTE format('REVOKE ALL ON TABLE %I FROM anon', t);
        END IF;
        IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
            EXECUTE format('REVOKE ALL ON TABLE %I FROM authenticated', t);
        END IF;
    END LOOP;
END $$;
